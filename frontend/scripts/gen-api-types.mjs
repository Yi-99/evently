// Regenerates src/api/schema.d.ts from the backend's OpenAPI document — no running server needed.
//
//   npm run api:types              (PYTHON=/path/to/python to override the interpreter)
//
// openapi-typescript drives the TypeScript 5 compiler API, which TypeScript 7 (the app's compiler)
// no longer ships, so it lives in tools/api-types with its own TypeScript 5 and is installed on first use.
import { execFileSync } from 'node:child_process'
import { existsSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const frontend = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const backend = resolve(frontend, '../backend')
const toolDir = join(frontend, 'tools/api-types')
const out = join(frontend, 'src/api/schema.d.ts')

// 1. Dump the OpenAPI document by building the app in-process (lifespan never runs, so no DB/Redis).
const python = process.env.PYTHON ?? join(backend, '.venv/bin/python')
if (!existsSync(python)) {
  console.error(`Python not found at ${python}. Create backend/.venv (task setup) or set PYTHON=...`)
  process.exit(1)
}
const env = { ...process.env, OTEL_ENABLED: 'false' }
delete env.ANTHROPIC_API_KEY
const json = execFileSync(
  python,
  ['-c', 'import json, sys; from app.main import app_factory; sys.stdout.write(json.dumps(app_factory().openapi()))'],
  { cwd: backend, env, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'inherit'] },
)
const document = JSON.parse(json)

// 2. Make sure the isolated openapi-typescript toolchain is installed.
if (!existsSync(join(toolDir, 'node_modules/openapi-typescript'))) {
  console.log('Installing openapi-typescript into tools/api-types …')
  execFileSync('npm', ['ci', '--no-audit', '--no-fund'], { cwd: toolDir, stdio: 'inherit' })
}
const entry = createRequire(join(toolDir, 'package.json')).resolve('openapi-typescript')
const { default: openapiTS, astToString } = await import(pathToFileURL(entry.replace(/\.cjs$/, '.mjs')).href)

// 3. Generate and write.
const ast = await openapiTS(document, { alphabetize: true })
const header = `/**
 * Generated by scripts/gen-api-types.mjs from the backend OpenAPI document (${document.info?.title} ${document.info?.version}).
 * Do not edit by hand — run \`npm run api:types\` after changing backend schemas.
 */

`
writeFileSync(out, header + astToString(ast))
console.log(`Wrote ${out} (${Object.keys(document.components?.schemas ?? {}).length} schemas, ${Object.keys(document.paths ?? {}).length} paths)`)
